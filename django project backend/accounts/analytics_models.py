# MODEL 4: MovieWatchHistory (Per-Movie Watch Time Tracking)
# ═══════════════════════════════════════════════════════════════════════════
# MongoDB Collection: 'movie_watch_history'
# Purpose: Track total watch time PER MOVIE for each user
# Used By: AI Recommendations (to understand which movies user spent most time on)
# ═══════════════════════════════════════════════════════════════════════════
class MovieWatchHistory(Document):
    """
    Track cumulative watch time per movie for each user
    
    DIFFERENCE FROM UserActivity:
        - UserActivity: Multiple records per movie (each watch session)
        - MovieWatchHistory: ONE record per user+movie combination
    
    Example:
        User "john" watches "Inception" 3 times:
        - UserActivity: 3 documents (session 1: 30min, session 2: 45min, session 3: 60min)
        - MovieWatchHistory: 1 document (total: 135 minutes)
    
    Why this model:
        - AI needs to know: Which movies user spent MOST time on
        - Fast query: Get top 10 most-watched movies per user
        - Better recommendations: Movies with high watch time = strong preference
    """
    meta = {
        'collection': 'movie_watch_history',
        'indexes': [
            {'fields': ['username', 'movie_id'], 'unique': True},  # One record per user+movie
            'username',  # Fast lookup by user
            '-total_watch_time_seconds'  # Fast sorting by watch time
        ]
    }
    
    # ─────────────────────────────────────────────────────────────────────
    # IDENTIFICATION
    # ─────────────────────────────────────────────────────────────────────
    username = StringField(required=True, max_length=100)
    # Which user
    
    movie_id = StringField(required=True, max_length=100)
    # Which movie (MongoDB ObjectId as string)
    
    movie_title = StringField(max_length=500)
    # Movie title (denormalized for fast display)
    
    movie_type = StringField(max_length=50)
    # "Movie" or "TV Show"
    
    # ─────────────────────────────────────────────────────────────────────
    # WATCH TIME TRACKING
    # ─────────────────────────────────────────────────────────────────────
    total_watch_time_seconds = IntField(default=0)
    # TOTAL time user spent watching this movie (all sessions combined)
    # Example: 7200 (2 hours total across multiple sessions)
    # Updated: Every time user watches (incremented)
    
    total_watch_time_minutes = IntField(default=0)
    # Same as above but in minutes (for display)
    # Example: 120 (2 hours)
    
    total_watch_time_hours = FloatField(default=0.0)
    # Same as above but in hours (for display)
    # Example: 2.0 (2 hours)
    
    watch_count = IntField(default=0)
    # How many times user watched this movie
    # Example: 3 (watched 3 separate times)
    # Incremented: Each time activity_type="movie_watch"
    
    watch_percentage = FloatField(default=0.0)
    # Current/last watch progress percentage (0-100)
    # Example: 75.5 (currently at 75.5% of movie)
    # Updated: Every time user watches, stores latest position
    # Used for: Continue Watching feature (show movies 5-90%)
    
    watching_percentage = IntField(default=0, min_value=0, max_value=100)
    # USER-EDITABLE percentage (0-100%)
    # Allows user to manually set/change their watch progress
    # Default: 0% until user changes it
    # Stored in MongoDB and counts for AI activity tracking
    # Different from watch_percentage (auto-calculated)
    
    completed = BooleanField(default=False)
    # Has user finished this movie? (watched 90%+)
    # Values: True/False
    # Updated: Set to True when watch_percentage >= 90
    
    # ─────────────────────────────────────────────────────────────────────
    # METADATA
    # ─────────────────────────────────────────────────────────────────────
    genres = ListField(StringField(max_length=100))
    # Movie genres (for quick filtering)
    # Example: ["Action", "Sci-Fi"]
    
    first_watched = DateTimeField(default=datetime.utcnow)
    # When user first watched this movie
    
    last_watched = DateTimeField(default=datetime.utcnow)
    # When user last watched this movie
    
    def __str__(self):
        return f"{self.username} - {self.movie_title} ({self.total_watch_time_minutes}min)"
    
    # Example MongoDB Document:
    # {
    #     "_id": ObjectId("..."),
    #     "username": "john",
    #     "movie_id": "abc123",
    #     "movie_title": "Inception",
    #     "movie_type": "Movie",
    #     "total_watch_time_seconds": 7200,
    #     "total_watch_time_minutes": 120,
    #     "watch_count": 3,
    #     "last_watch_percentage": 100.0,
    #     "highest_watch_percentage": 100.0,
    #     "completed": "yes",
    #     "genres": ["Action", "Sci-Fi", "Thriller"],
    #     "first_watched": ISODate("2024-01-10T..."),
    #     "last_watched": ISODate("2024-01-15T...")
    # }


