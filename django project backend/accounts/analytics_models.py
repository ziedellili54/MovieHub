# MODEL 2: UserPreferences (Aggregated User Patterns)
# ═══════════════════════════════════════════════════════════════════════════
# MongoDB Collection: 'user_preferences'
# Purpose: ONE document per user with aggregated behavior data
# Used By: TrackActivityView updates this, GetUserAnalyticsView reads it
# Updated: Automatically when UserActivity is created
# ═══════════════════════════════════════════════════════════════════════════
class UserPreferences(Document):
    """
    Store aggregated user preferences and behavior patterns
    
    DIFFERENCE FROM UserActivity:
        - UserActivity: Every single action (1000s of documents per user)
        - UserPreferences: Summarized data (1 document per user)
    
    Example:
        - UserActivity has 500 "movie_watch" records for "john"
        - UserPreferences has: total_movies_watched = 500
    
    Why separate models:
        - Fast queries: Get user summary without scanning 1000s of activities
        - Recommendations: Quickly find favorite genres
        - Dashboard: Show user stats without heavy calculations
    """
    meta = {'collection': 'user_preferences'}
    
    username = StringField(required=True, unique=True, max_length=100)
    # One document per user (unique=True)
    # Example: "john"
    
    # ─────────────────────────────────────────────────────────────────────
    # VIEWING PREFERENCES
    # ─────────────────────────────────────────────────────────────────────
    favorite_genres = ListField(StringField())
    # Most watched genres (aggregated from UserActivity)
    # Example: ["Action", "Sci-Fi", "Thriller"]
    # Updated: Every time user watches movie with new genre
    # Used for: Personalized recommendations
    
    favorite_actors = ListField(StringField())
    # Most watched actors (future feature)
    # Example: ["Leonardo DiCaprio", "Tom Hardy"]
    
    favorite_directors = ListField(StringField())
    # Most watched directors (future feature)
    # Example: ["Christopher Nolan", "Quentin Tarantino"]
    
    # ─────────────────────────────────────────────────────────────────────
    # BEHAVIOR PATTERNS
    # ─────────────────────────────────────────────────────────────────────
    average_watch_percentage = FloatField()
    # On average, how much of movies they watch
    # Example: 85.5 (watches 85.5% on average)
    # Calculated from: Average of UserActivity.watch_percentage
    
    completion_rate = FloatField()
    # Percentage of movies they finish (watch 90%+)
    # Example: 65.0 (finishes 65% of started movies)
    
    preferred_duration = StringField()
    # Preferred movie length
    # Values: "short" (<90 min), "medium" (90-150), "long" (>150)
    
    preferred_type = StringField()
    # "Movie" or "TV Show" preference
    # Calculated: Which type they watch more
    
    # ─────────────────────────────────────────────────────────────────────
    # TIME PATTERNS
    # ─────────────────────────────────────────────────────────────────────
    most_active_time = StringField()
    # When they usually watch
    # Values: "morning" (6-12), "afternoon" (12-18), "evening" (18-24), "night" (0-6)
    # Used to: Send notifications at optimal time
    
    average_session_duration_minutes = IntField()
    # Average time per app session
    # Example: 45 (45 minutes per session)
    
    total_time_spent_minutes = IntField()
    # Total time ever spent in app
    # Example: 15000 (250 hours total)
    
    # ─────────────────────────────────────────────────────────────────────
    # ENGAGEMENT METRICS (Counters)
    # ─────────────────────────────────────────────────────────────────────
    total_movies_watched = IntField(default=0)
    # How many movies watched (any amount)
    # Incremented: When activity_type="movie_watch"
    
    total_movies_liked = IntField(default=0)
    # How many movies liked
    # Incremented: When activity_type="like"
    
    total_movies_disliked = IntField(default=0)
    # How many movies disliked
    # Incremented: When activity_type="dislike"
    
    total_searches = IntField(default=0)
    # How many searches performed
    # Incremented: When activity_type="search"
    
    watchlist_size = IntField(default=0)
    # Current watchlist count (future feature)
    
    # ─────────────────────────────────────────────────────────────────────
    # DEVICE PREFERENCES
    # ─────────────────────────────────────────────────────────────────────
    primary_device = StringField()
    # Most used device
    # Example: "desktop", "mobile"
    # Calculated: Device with most activities
    
    devices_used = ListField(StringField())
    # All devices ever used
    # Example: ["desktop", "mobile", "tablet"]
    
    # ─────────────────────────────────────────────────────────────────────
    # GEOGRAPHIC
    # ─────────────────────────────────────────────────────────────────────
    country = StringField()
    # User's country
    # Example: "USA"
    # Used for: Content licensing, regional recommendations
    
    # ─────────────────────────────────────────────────────────────────────
    # PURCHASE HISTORY (Future Feature)
    # ─────────────────────────────────────────────────────────────────────
    total_purchases = IntField(default=0)
    # Number of purchases made
    
    last_purchase_date = DateTimeField()
    # When last purchase was made
    
    # ─────────────────────────────────────────────────────────────────────
    # RECOMMENDATIONS METADATA
    # ─────────────────────────────────────────────────────────────────────
    recommendation_score = DictField()
    # Genre scores for recommendation algorithm
    # Example: {"Action": 95, "Drama": 75, "Comedy": 50}
    # Higher score = recommend more of that genre
    
    # ─────────────────────────────────────────────────────────────────────
    # TIMESTAMPS
    # ─────────────────────────────────────────────────────────────────────
    created_at = DateTimeField(default=datetime.utcnow)
    # When preferences document was created
    
    updated_at = DateTimeField(default=datetime.utcnow)
    # When preferences were last updated
    
    last_activity = DateTimeField()
    # When user was last active
    # Used to: Identify inactive users
    
    def __str__(self):
        return f"Preferences for {self.username}"


