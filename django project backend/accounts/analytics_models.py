# MODEL 3: UserSession (Session Tracking)
# ═══════════════════════════════════════════════════════════════════════════
# MongoDB Collection: 'user_sessions'
# Purpose: Track each time user opens/closes app
# Used By: StartSessionView, EndSessionView in analytics_views.py
# ═══════════════════════════════════════════════════════════════════════════
class UserSession(Document):
    """
    Track user sessions for time spent analytics
    
    SESSION LIFECYCLE:
        1. User opens app
        2. Frontend: POST /api/analytics/session/start/
        3. Creates UserSession with session_start
        4. Returns session_id to frontend
        5. User uses app (session_id included in all activities)
        6. User closes app
        7. Frontend: POST /api/analytics/session/end/ {session_id}
        8. Updates UserSession with session_end, duration_seconds
    
    Use Cases:
        - Calculate average session duration
        - Identify peak usage times
        - Track concurrent users
        - Detect abandoned sessions (started but never ended)
    """
    meta = {'collection': 'user_sessions'}
    
    username = StringField(required=True, max_length=100)
    # Which user this session belongs to
    
    session_id = StringField(required=True, unique=True, max_length=100)
    # Unique identifier for this session
    # Generated by: StartSessionView using uuid.uuid4()
    # Example: "a1b2c3d4-e5f6-7890-abcd-ef1234567890"
    # Used to: Link UserActivity records to this session
    
    # ─────────────────────────────────────────────────────────────────────
    # SESSION TIMING
    # ─────────────────────────────────────────────────────────────────────
    session_start = DateTimeField(default=datetime.utcnow)
    # When user opened app
    # Set automatically when document created
    
    session_end = DateTimeField()
    # When user closed app
    # Set by: EndSessionView
    # None = Session still active or abandoned
    
    duration_seconds = IntField()
    # How long session lasted
    # Calculated: session_end - session_start
    # Example: 2700 (45 minutes)
    # Set by: EndSessionView
    
    # ─────────────────────────────────────────────────────────────────────
    # ACTIVITY DURING SESSION
    # ─────────────────────────────────────────────────────────────────────
    pages_visited = ListField(StringField())
    # Which pages user visited
    # Example: ["/dashboard", "/movie/123", "/search"]
    # (Future feature - not currently populated)
    
    movies_viewed = ListField(StringField())
    # Which movies user viewed
    # Example: ["abc123", "xyz789"]
    # (Future feature - not currently populated)
    
    searches_count = IntField(default=0)
    # How many searches in this session
    # (Future feature - not currently populated)
    
    # ─────────────────────────────────────────────────────────────────────
    # DEVICE INFO
    # ─────────────────────────────────────────────────────────────────────
    device_type = StringField()
    # "desktop", "mobile", "tablet"
    
    browser = StringField()
    # "Chrome", "Firefox", etc.
    
    os = StringField()
    # "Windows 10", "Android", etc.
    
    country = StringField()
    # "USA", "UK", etc.
    
    ip_address = StringField()
    # User's IP address
    
    # ─────────────────────────────────────────────────────────────────────
    # STATUS
    # ─────────────────────────────────────────────────────────────────────
    is_active = StringField(default='active')
    # Session status
    # Values: "active" (ongoing), "ended" (closed)
    # Updated by: EndSessionView
    
    def __str__(self):
        return f"{self.username} - Session {self.session_id}"

