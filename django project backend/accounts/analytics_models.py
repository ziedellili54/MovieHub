from datetime import datetime


# ═══════════════════════════════════════════════════════════════════════════
# MODEL 1: UserActivity (Individual User Actions)
# ═══════════════════════════════════════════════════════════════════════════
# MongoDB Collection: 'user_activities'
# Purpose: Log EVERY user action for detailed analytics
# Used By: TrackActivityView in analytics_views.py
# Example: User searches "action" → Creates UserActivity with activity_type="search"
# ═══════════════════════════════════════════════════════════════════════════
class UserActivity(Document):
    """
    Track all user activities and interactions
    
    This model creates a detailed log of everything users do:
    - Every search they make
    - Every movie they click
    - Every video they watch (with watch time)
    - Every like/dislike
    
    Use Cases:
        - Admin dashboard: See most searched movies
        - Recommendations: Suggest similar movies to what user watches
        - Analytics: Average watch time, completion rate
        - Business insights: Popular genres, peak usage times
    
    Example Flow:
        1. User searches "batman"
        2. Frontend: analyticsService.trackActivity({
             username: "john",
             activity_type: "search",
             search_query: "batman"
           })
        3. Backend: POST /api/analytics/track/
        4. Creates UserActivity document in MongoDB
    """
    meta = {'collection': 'user_activities'}
    
    # ─────────────────────────────────────────────────────────────────────
    # USER IDENTIFICATION
    # ─────────────────────────────────────────────────────────────────────
    username = StringField(required=True, max_length=100)
    # Which user performed this activity
    # Links to: accounts.models.User.username
    # Example: "john", "jane"
    
    session_id = StringField(max_length=100)
    # Groups activities from same app session
    # Generated by: StartSessionView in analytics_views.py
    # Example: "session_1234567890_abc123"
    # Used to: Calculate session duration, activities per session
    
    # ─────────────────────────────────────────────────────────────────────
    # ACTIVITY DETAILS
    # ─────────────────────────────────────────────────────────────────────
    activity_type = StringField(required=True, max_length=50)
    # ACTIVITY TYPES (what user did):
    #   - "app_open" → User opened the app
    #   - "search" → User searched for something
    #   - "movie_click" → User clicked on a movie card
    #   - "movie_play" → User started playing video
    #   - "movie_watch" → User watched (tracked periodically)
    #   - "movie_finish" → User finished watching
    #   - "add_watchlist" → Added to watchlist
    #   - "remove_watchlist" → Removed from watchlist
    #   - "like" → Liked a movie
    #   - "dislike" → Disliked a movie
    #   - "purchase" → Purchased/rented movie
    #   - "browse" → Browsed movies list
    #
    # Why we track these:
    #   - Understand user preferences
    #   - Improve recommendations
    #   - Measure engagement
    
    # ─────────────────────────────────────────────────────────────────────
    # MOVIE/CONTENT RELATED (when activity involves a movie)
    # ─────────────────────────────────────────────────────────────────────
    movie_id = StringField(max_length=100)
    # Which movie this activity relates to
    # Links to: movies.models.Movie.id or TVShow.id
    # Example: "507f1f77bcf86cd799439011"
    # Optional: Only set if activity involves specific movie
    
    movie_title = StringField(max_length=500)
    # Movie title for easy reporting (avoid joining collections)
    # Example: "Inception", "Breaking Bad"
    # Denormalized: Stored here even though it's also in movies collection
    # Why: Faster queries (don't need to join movies collection)
    
    movie_type = StringField(max_length=50)
    # "Movie" or "TV Show"
    # Used to: Analyze if user prefers movies vs shows
    
    # ─────────────────────────────────────────────────────────────────────
    # SEARCH RELATED (when activity_type = "search")
    # ─────────────────────────────────────────────────────────────────────
    search_query = StringField(max_length=500)
    # What user searched for
    # Example: "action movies", "batman", "2024"
    # Used to:
    #   - Popular searches dashboard
    #   - Autocomplete suggestions
    #   - Improve search algorithm
    
    search_results_count = IntField()
    # How many results returned for search
    # Example: 42
    # Used to: Identify searches with no/few results (need more content)
    
    # ─────────────────────────────────────────────────────────────────────
    # WATCH RELATED (when activity_type = "movie_watch")
    # ─────────────────────────────────────────────────────────────────────
    watch_duration_seconds = IntField()
    # How long user watched THIS session
    # Example: 1800 (30 minutes)
    # Can be multiple activities for same movie as user watches
    
    watch_percentage = FloatField()
    # Progress percentage (0-100)
    # Example: 75.5 (watched 75.5% of movie)
    # Used to: Calculate completion rate
    
    total_duration_seconds = IntField()
    # Total length of movie/episode
    # Example: 7200 (2 hour movie)
    # Used to: Calculate watch_percentage
    
    # ─────────────────────────────────────────────────────────────────────
    # CATEGORY/GENRE
    # ─────────────────────────────────────────────────────────────────────
    category = StringField(max_length=200)
    # Broad category (not heavily used)
    # Example: "Action", "Entertainment"
    
    genres = ListField(StringField(max_length=100))
    # List of genres for this movie
    # Example: ["Action", "Sci-Fi", "Thriller"]
    # Used to: Identify user's favorite genres
    # Aggregated in: UserPreferences.favorite_genres
    
    # ─────────────────────────────────────────────────────────────────────
    # DEVICE & LOCATION
    # ─────────────────────────────────────────────────────────────────────
    device_type = StringField(max_length=50)
    # "desktop", "mobile", "tablet"
    # Used to: Optimize UI for most-used device
    
    browser = StringField(max_length=100)
    # "Chrome", "Firefox", "Safari", "Edge"
    # Used to: Fix browser-specific bugs
    
    os = StringField(max_length=100)
    # "Windows 10", "macOS", "Android", "iOS"
    # Used to: Prioritize platform support
    
    country = StringField(max_length=100)
    # "USA", "UK", "France"
    # Used to: Geographic analytics, content licensing
    
    ip_address = StringField(max_length=50)
    # Example: "192.168.1.1"
    # Used to: Detect multiple accounts from same IP (fraud detection)
    
    # ─────────────────────────────────────────────────────────────────────
    # TIME TRACKING
    # ─────────────────────────────────────────────────────────────────────
    timestamp = DateTimeField(default=datetime.utcnow)
    # When this activity happened
    # Automatically set to current UTC time
    # Used to: Sort activities, calculate time-based metrics
    
    watched_at = DateTimeField()
    # Legacy field from old system (kept for compatibility)
    # Same as timestamp in most cases
    
    session_start = DateTimeField()
    # When user's session started
    # Copied from: UserSession.session_start
    # Used to: Calculate time from session start to this activity
    
    time_spent_seconds = IntField()
    # How long user spent on this specific activity
    # Example: 120 (2 minutes on movie details page)
    
    # ─────────────────────────────────────────────────────────────────────
    # ADDITIONAL METADATA
    # ─────────────────────────────────────────────────────────────────────
    metadata = DictField()
    # Flexible field for future data
    # Example: {
    #   "video_quality": "1080p",
    #   "subtitle_language": "English",
    #   "playback_speed": 1.5
    # }
    
    def __str__(self):
        # String representation for debugging
        # Example: "john - search - 2024-01-15 10:30:00"
        return f"{self.username} - {self.activity_type} - {self.timestamp}"
    
    # Example MongoDB Document:
    # {
    #     "_id": ObjectId("..."),
    #     "username": "john",
    #     "session_id": "session_123",
    #     "activity_type": "movie_watch",
    #     "movie_id": "abc123",
    #     "movie_title": "Inception",
    #     "movie_type": "Movie",
    #     "watch_duration_seconds": 1800,
    #     "watch_percentage": 25.0,
    #     "total_duration_seconds": 7200,
    #     "genres": ["Action", "Sci-Fi"],
    #     "device_type": "desktop",
    #     "browser": "Chrome",
    #     "timestamp": ISODate("2024-01-15T10:30:00Z")
    # }


