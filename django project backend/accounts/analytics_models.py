class UserPersonalizedSections(Document):
    """
    Store personalized dashboard sections for each user
    
    CONCEPT:
    - Same content for all users (e.g., Top Watched Movies)
    - But SORTED differently based on user's genre preferences
    - Updated when user preferences change, not recreated
    
    SECTIONS STORED:
    1. AI Recommendations (already generated)
    2. Top Watched Movies (all-time)
    3. Top Watched Series (all-time)
    4. Top Searched Movies (most searched)
    5. Top Searched Series (most searched)
    6. Top 10 Movies (best rated/popular)
    7. Top 10 Series (best rated/popular)
    8. Top 20 Favorites (most favorited by all users)
    9. Newly Added Movies (recently added to DB)
    10. Newly Added Series (recently added to DB)
    
    HOW IT WORKS:
    1. Global data is same (e.g., "most watched movies")
    2. AI sorts by user's preferred genres first
    3. Saved here for fast loading
    4. Updated when:
       - User changes genre preferences
       - User watches new content
       - New global data available (hourly)
    """
    meta = {
        'collection': 'user_personalized_sections',
        'indexes': [
            {'fields': ['username'], 'unique': True},
            '-last_updated'
        ]
    }
    
    # ─────────────────────────────────────────────────────────────────────
    # USER IDENTIFICATION
    # ─────────────────────────────────────────────────────────────────────
    username = StringField(required=True, unique=True, max_length=100)
    
    # ─────────────────────────────────────────────────────────────────────
    # SECTION 1: AI RECOMMENDATIONS (20 movies)
    # ─────────────────────────────────────────────────────────────────────
