    # CALCULATION:
    #   Position 1-5:    +10 points each (EXCELLENT - user loved top picks)
    #   Position 6-10:   +5 points each (GOOD - still top 10)
    #   Position 11-20:  0 points (NEUTRAL - acceptable)
    #   Position 21-50:  -1 per position (BAD - skipped better options)
    #   Position 51+:    -2 per position (VERY BAD - ignored much better matches)
    #
    # Examples:
    #   Clicked position 1:  +10 (perfect!)
    #   Clicked position 8:  +5 (great!)
    #   Clicked position 15: 0 (okay)
    #   Clicked position 30: -10 (not great)
    #   Clicked position 80: -60 (AI failed badly)
    
    feedback_category = StringField()
    # Human-readable category
    # Values:
    #   "excellent" (pos 1-5)
    #   "good" (pos 6-10)
    #   "neutral" (pos 11-20)
    #   "bad" (pos 21-50)
    #   "very_bad" (pos 51+)
    
    # ─────────────────────────────────────────────────────────────────────
    # USER STATE AT TIME OF RECOMMENDATION
    # ─────────────────────────────────────────────────────────────────────
    user_favorite_genres_at_time = ListField(StringField())
    # User's favorite genres when recommendation was made
    # Example: ["Action", "Sci-Fi"]
    # Used to: Understand what user profile led to this result
    
    user_activity_count = IntField()
    # How many activities user had
    # More activities = AI should perform better
    
    # ─────────────────────────────────────────────────────────────────────
    # OTHER RECOMMENDATIONS IN BATCH
    # ─────────────────────────────────────────────────────────────────────
    total_recommendations_in_batch = IntField()
    # How many movies were recommended
    # Usually: 100
    
    skipped_count = IntField()
    # How many movies user skipped before this one
    # Example: 29 (skipped positions 1-29, clicked 30)
    
    # ─────────────────────────────────────────────────────────────────────
    # TIMESTAMPS
    # ─────────────────────────────────────────────────────────────────────
    recommended_at = DateTimeField(required=True)
    # When recommendations were generated
    
    clicked_at = DateTimeField(default=datetime.utcnow)
    # When user clicked
    
    time_to_click_seconds = IntField()
    # How long between showing and clicking
    # Example: 45 (45 seconds to decide)
    
    timestamp = DateTimeField(default=datetime.utcnow)
    # When feedback was recorded
    
    def __str__(self):
        return f"{self.username} - Pos {self.recommendation_position} ({self.feedback_category}) - {self.feedback_score} pts"
    
