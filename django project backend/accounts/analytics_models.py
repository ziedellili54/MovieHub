# MODEL 6: MovieDislike (Hidden Dislikes for AI Learning)
# ═══════════════════════════════════════════════════════════════════════════
# MongoDB Collection: 'movie_dislikes'
# Purpose: Track disliked movies (hidden from user, used by AI)
# Used By: AI to filter recommendations, hide from all views
# ═══════════════════════════════════════════════════════════════════════════
class MovieDislike(Document):
    """
    Track movies user has disliked
    
    CRITICAL DIFFERENCES FROM FAVORITES:
    - Favorites: Visible to user, adds to profile
    - Dislikes: HIDDEN from user, removes from everywhere
    
    HOW IT WORKS:
    1. User clicks "👎 Dislike" button
    2. Movie saved here (not shown to user like favorites)
    3. Movie DISAPPEARS from:
       - AI Recommendations
       - Trending section
       - Continue Watching
       - Search results (optional)
       - ALL packs
    4. AI learns: This genre/pattern doesn't work
    5. If AI recommended it: AI gets negative points
    
    PURPOSE:
    - Filter unwanted content
    - Improve AI recommendations
    - Penalize AI for bad suggestions
    - Learn genre/actor/director dislikes
    """
    meta = {
        'collection': 'movie_dislikes',
        'indexes': [
            {'fields': ['username', 'movie_id'], 'unique': True},  # One dislike per user+movie
            'username',
            '-disliked_at'
        ]
    }
    
    # ─────────────────────────────────────────────────────────────────────
    # IDENTIFICATION
    # ─────────────────────────────────────────────────────────────────────
    username = StringField(required=True, max_length=100)
    movie_id = StringField(required=True, max_length=100)
    movie_title = StringField(max_length=500)
    movie_type = StringField(max_length=50)
    
    # ─────────────────────────────────────────────────────────────────────
    # DISLIKE CONTEXT
    # ─────────────────────────────────────────────────────────────────────
    genres = ListField(StringField(max_length=100))
    director = StringField(max_length=200)
    cast = StringField(max_length=500)
    dislike_reason = StringField(max_length=50)
    
    # ─────────────────────────────────────────────────────────────────────
    # AI IMPACT
    # ─────────────────────────────────────────────────────────────────────
    was_ai_recommendation = BooleanField(default=False)
    recommendation_position = IntField()
    ai_penalty_applied = BooleanField(default=False)
    ai_penalty_score = IntField(default=0)
    
    # ─────────────────────────────────────────────────────────────────────
    # FILTER SETTINGS
    # ─────────────────────────────────────────────────────────────────────
    hide_from_recommendations = BooleanField(default=True)
    hide_from_trending = BooleanField(default=True)
    hide_from_search = BooleanField(default=False)
    hide_similar_movies = BooleanField(default=False)
    
    # ─────────────────────────────────────────────────────────────────────
    # GENRE/PATTERN LEARNING
    # ─────────────────────────────────────────────────────────────────────
    genre_penalty_weights = DictField()
    
    # ─────────────────────────────────────────────────────────────────────
    # TIMESTAMPS
    # ─────────────────────────────────────────────────────────────────────
    disliked_at = DateTimeField(default=datetime.utcnow)
    last_filtered_at = DateTimeField()
    
    def __str__(self):
        return f"{self.username} dislikes {self.movie_title}"


