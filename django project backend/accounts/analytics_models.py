    # SECTION 2: TOP WATCHED MOVIES (All-time most watched, sorted by user genres)
    # ─────────────────────────────────────────────────────────────────────
    top_watched_movies = ListField(StringField())  # List of movie_ids
    top_watched_movies_scores = DictField()  # {movie_id: watch_count}
    
